function renderBackupListeners() {
  qs("#exportBackup").addEventListener("click", () => {
    const payload = { equipment, inventory, tasks, maintenanceRecords, staff };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "respaldo-valleflor.json";
    a.click();
    URL.revokeObjectURL(url);
  });

  qs("#importBackup").addEventListener("click", () => {
    try {
      const data = JSON.parse(qs("#importPayload").value);
      if (!data) return alert("Pegue un JSON válido");
      equipment.length = 0;
      inventory.length = 0;
      tasks.length = 0;
      maintenanceRecords.length = 0;
      staff.length = 0;
      equipment.push(...(data.equipment || []));
      inventory.push(...(data.inventory || []));
      tasks.push(...(data.tasks || []));
      maintenanceRecords.push(...(data.maintenanceRecords || []));
      staff.push(...(data.staff || []));
      state.filters = { finca: "Todos", category: "Todos", year: "Todos", type: "Todos" };
      state.planning = { finca: "Todas", status: "Todas", selectedDate: new Date().toISOString().slice(0, 10) };
      initFilters();
      renderEquipment();
      renderInventory();
      renderRecentMaintenance();
      renderLife();
      renderStaff();
      renderInventorySearchLabels();
      renderCalendar(qs("#planningMonth").value);
      renderKPIs();
      renderTaskDetails();
      alert("Datos restaurados");
    } catch (err) {
      alert("JSON inválido");
    }
  });
}


function renderStatusBadge(status) {
  const text = status === "OPERATIVO" ? "Operativo" : "Fuera de servicio";
  const color = status === "OPERATIVO" ? "badge" : "chip corrective";
  return `<span class="${color}">${text}</span>`;
}

function onEquipmentStatusChange(ev) {
  const id = Number(ev.target.dataset.id);
  const value = ev.target.value;
  const eq = equipment.find((e) => e.id === id);
  if (!eq) return;
  eq.status = value;
  if (value !== "OPERATIVO") {
    const today = new Date().toISOString().slice(0, 10);
    tasks = tasks.filter((t) => !(t.equipmentId === id && t.date > today && t.autoGenerated));
  } else {
    generatePreventiveTasksFor(id);
  }
  renderCalendar(qs("#planningMonth").value);
  renderKPIs();
}


function generatePreventiveTasksFor(equipmentId) {
  const eq = equipment.find((e) => e.id === equipmentId);
  if (!eq || eq.status !== "OPERATIVO") return;
  const lastDate = new Date(eq.lastMaintenance);
  for (let i = 1; i <= 12; i++) {
    const next = new Date(lastDate.getFullYear(), lastDate.getMonth() + i, lastDate.getDate());
    let day = next.getDay();
    if (day === 0) next.setDate(next.getDate() + 1);
    if (day === 6) next.setDate(next.getDate() + 2);
    const dateStr = next.toISOString().slice(0, 10);
    if (!tasks.some((t) => t.equipmentId === eq.id && t.date === dateStr && t.autoGenerated)) {
      tasks.push({
        id: crypto.randomUUID(),
        date: dateStr,
        equipmentId: eq.id,
        type: "Preventivo",
        description: "Preventivo mensual",
        status: "Planificado",
        cost: 0,
        notes: "Generado automáticamente",
        autoGenerated: true
      });
    }
  }
}

function regeneratePreventives() {
  tasks = tasks.filter((t) => !t.autoGenerated);
  equipment.forEach((eq) => generatePreventiveTasksFor(eq.id));
  renderCalendar(qs("#planningMonth").value);
}


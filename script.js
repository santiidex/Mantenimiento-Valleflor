function initFilters() {
  const fincas = ["Todos", ...new Set(equipment.map((e) => e.finca))];
  const categories = ["Todos", ...new Set(equipment.map((e) => e.category))];
  const years = ["Todos", ...new Set(maintenanceRecords.map((r) => new Date(r.date).getFullYear()))];
  const types = ["Todos", "Preventivo", "Correctivo", "Predictivo", "Inspección", "Calibración"];

  fillSelect("dashboardFincaFilter", fincas);
  fillSelect("dashboardCategoryFilter", categories);
  fillSelect("dashboardYearFilter", years);
  fillSelect("dashboardTypeFilter", types);
  fillSelect("taskEquipment", equipment.map((e) => ({ label: `${e.code} - ${e.name}`, value: e.id })));
  fillSelect("taskResponsible", staff.map((s) => ({ label: s.name, value: s.name })));
  fillSelect("lifeFinca", fincas.filter((f) => f !== "Todos"));
  fillSelect("lifeEquipment", equipment.map((e) => ({ label: e.code, value: e.id })));
  fillSelect("planningMonth", generateMonths(), true);
  fillSelect("planningFinca", ["Todas", ...fincas.filter((f) => f !== "Todos")]);
}

function fillSelect(id, values, isMonth = false) {
  const el = qs(`#${id}`);
  el.innerHTML = "";
  values.forEach((val) => {
    const option = document.createElement("option");
    option.value = isMonth ? val.value : typeof val === "object" ? val.value : val;
    option.textContent = typeof val === "object" ? val.label : val;
    el.appendChild(option);
  });
}

function generateMonths() {
  const months = [];
  const today = new Date();
  for (let i = 0; i < 12; i++) {
    const date = new Date(today.getFullYear(), today.getMonth() + i, 1);
    const iso = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}`;
    months.push({ label: date.toLocaleString("es", { month: "long", year: "numeric" }), value: iso });
  }
  return months;
}

function renderKPIs() {
  const filtered = filterRecords();
  const filteredEquipment = filterEquipment();
  const costTotal = filtered.reduce((sum, r) => sum + Number(r.cost || 0), 0);
  const preventive = filtered.filter((r) => r.type === "Preventivo").length;
  const correctivo = filtered.filter((r) => r.type === "Correctivo").length;
  const avgCost = filtered.length ? costTotal / filtered.length : 0;
  const equipmentWithMaintenance = new Set(filtered.map((r) => r.equipmentId));
  const equipmentWithoutMaintenance = filteredEquipment.filter((eq) => !equipmentWithMaintenance.has(eq.id)).length;
  const percentPreventivo = filtered.length ? Math.round((preventive / filtered.length) * 100) : 0;
  const percentCorrectivo = filtered.length ? Math.round((correctivo / filtered.length) * 100) : 0;
  const kpis = [
    { label: "Equipos filtrados", value: filteredEquipment.length },
    { label: "Mantenimientos filtrados", value: filtered.length },
    { label: "Costo total", value: `$${costTotal.toFixed(2)}` },
    { label: "Costo promedio", value: `$${avgCost.toFixed(2)}` },
    { label: "Preventivo vs Correctivo", value: `${percentPreventivo}% / ${percentCorrectivo}%` },
    { label: "Equipos sin mantenimiento", value: equipmentWithoutMaintenance }
  ];
  qs("#kpiGrid").innerHTML = kpis
    .map((k) => `<div class="kpi"><span>${k.label}</span><strong>${k.value}</strong></div>`) 
    .join("");

  renderCharts(filtered);
  renderSummaryByFinca(filtered, filteredEquipment);
}

function filterRecords() {
  return maintenanceRecords.filter((r) => {
    const eq = equipment.find((e) => e.id === r.equipmentId);
    const matchesFinca = state.filters.finca === "Todos" || eq?.finca === state.filters.finca;
    const matchesCategory = state.filters.category === "Todos" || eq?.category === state.filters.category;
    const matchesYear = state.filters.year === "Todos" || new Date(r.date).getFullYear().toString() === state.filters.year.toString();
    const matchesType = state.filters.type === "Todos" || r.type === state.filters.type;
    return matchesFinca && matchesCategory && matchesYear && matchesType;
  });
}

function filterEquipment() {
  return equipment.filter((eq) => {
    const matchesFinca = state.filters.finca === "Todos" || eq.finca === state.filters.finca;
    const matchesCategory = state.filters.category === "Todos" || eq.category === state.filters.category;
    return matchesFinca && matchesCategory;
  });
}

function renderCharts(records) {
  const countsByType = records.reduce((acc, r) => {
    acc[r.type] = (acc[r.type] || 0) + 1;
    return acc;
  }, {});
  qs("#taskChart").innerHTML = `<h3>Distribución por tipo</h3><div class="bars">${Object.entries(countsByType)
    .map(([t, c]) => `<div class="bar" style="height:${30 + c * 15}px"><span>${t}</span><strong>${c}</strong></div>`)
    .join("")}</div>`;

  const costsByFinca = records.reduce((acc, r) => {
    const finca = equipment.find((e) => e.id === r.equipmentId)?.finca || "N/D";
    acc[finca] = (acc[finca] || 0) + Number(r.cost || 0);
    return acc;
  }, {});
  qs("#costChart").innerHTML = `<h3>Mantenimientos por finca</h3><div class="bars">${Object.entries(costsByFinca)
    .map(([m, c]) => `<div class="bar bar-secondary" style="height:${30 + c / 10}px"><span>${m}</span><strong>$${c.toFixed(0)}</strong></div>`)
    .join("")}</div>`;

  const workload = records.reduce((acc, r) => {
    const key = r.responsible || "Sin responsable";
    acc[key] = (acc[key] || 0) + 1;
    return acc;
  }, {});
  qs("#workloadChart").innerHTML = `<h3>Carga por responsable</h3><div class="bars">${Object.entries(workload)
    .map(([person, count]) => `<div class="bar" style="height:${30 + count * 15}px"><span>${person}</span><strong>${count}</strong></div>`)
    .join("")}</div>`;
}

function renderSummaryByFinca(records, filteredEquipment) {
  const fincas = [...new Set(filteredEquipment.map((eq) => eq.finca))];
  const summary = fincas.map((finca) => {
    const eqCount = filteredEquipment.filter((eq) => eq.finca === finca).length;
    const maint = records.filter((r) => equipment.find((e) => e.id === r.equipmentId)?.finca === finca);
    const maintCount = maint.length;
    const cost = maint.reduce((sum, r) => sum + Number(r.cost || 0), 0);
    return { finca, eqCount, maintCount, cost };
  });

  qs("#summaryByFinca").innerHTML = summary
    .map(
      (row) => `
      <div class="summary-card">
        <h3>${row.finca}</h3>
        <p>${row.eqCount} equipos</p>
        <p>${row.maintCount} mantenimientos</p>
        <p>Costos: $${row.cost.toFixed(0)}</p>
      </div>
    `
    )
    .join("") || "<p>Sin datos filtrados</p>";
}

function renderCalendar(monthValue) {
  const calendar = qs("#calendar");
  const [year, month] = monthValue ? monthValue.split("-") : new Date().toISOString().split("-");
  const firstDay = new Date(Number(year), Number(month) - 1, 1);
  const daysInMonth = new Date(Number(year), Number(month), 0).getDate();
  const startDay = firstDay.getDay();
  const labels = ["Dom", "Lun", "Mar", "Mié", "Jue", "Vie", "Sáb"];

  const monthTasks = tasks
    .filter((t) => new Date(t.date).getMonth() + 1 === Number(month) && new Date(t.date).getFullYear() === Number(year))
    .filter((t) => {
      const eq = equipment.find((e) => e.id === t.equipmentId);
      const matchesFinca = state.planning.finca === "Todas" || eq?.finca === state.planning.finca;
      const status = deriveTaskStatus(t);
      const matchesStatus = state.planning.status === "Todas" || status === state.planning.status;
      return matchesFinca && matchesStatus;
    });

  calendar.innerHTML = `
    <div class="calendar-header">
      <div class="badge">${firstDay.toLocaleString("es", { month: "long", year: "numeric" })}</div>
      <div style="text-align:right;color:var(--muted)">Tareas visibles en la cuadrícula</div>
    </div>
    <div class="calendar-weekdays">${labels.map((d) => `<div class="muted">${d}</div>`).join("")}</div>
    <div class="calendar-days"></div>
  `;

  const daysContainer = calendar.querySelector(".calendar-days");
  for (let i = 0; i < startDay; i++) {
    daysContainer.appendChild(document.createElement("div"));
  }
  for (let day = 1; day <= daysInMonth; day++) {
    const dateStr = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
    const cell = document.createElement("div");
    cell.className = "calendar-day";
    const dayTasks = monthTasks.filter((t) => t.date === dateStr);
    const displayChips = dayTasks.slice(0, 2)
      .map((t) => `<div class="chip ${t.type.toLowerCase()}">${t.type} - ${equipment.find((e) => e.id === t.equipmentId)?.code || ""}</div>`)
      .join("");
    const overflow = dayTasks.length > 2 ? `<div class="chip muted">+${dayTasks.length - 2} más</div>` : "";
    cell.innerHTML = `<div class="date">${day}</div>${displayChips}${overflow}`;
    cell.addEventListener("click", () => {
      qs("#taskDate").value = dateStr;
      state.planning.selectedDate = dateStr;
      renderTaskDetails();
      qs("#taskDescription").focus();
    });
    daysContainer.appendChild(cell);
  }
}

function handleTaskSubmit(e) {
  e.preventDefault();
  const payload = {
    id: crypto.randomUUID(),
    date: qs("#taskDate").value,
    equipmentId: Number(qs("#taskEquipment").value),
    responsible: qs("#taskResponsible").value,
    type: qs("#taskType").value,
    description: qs("#taskDescription").value,
    status: qs("#taskStatus").value,
    cost: Number(qs("#taskCost").value || 0),
    notes: qs("#taskNotes").value,
    autoGenerated: false,
    createMaintenance: qs("#taskCreateMaintenance").checked
  };
  tasks.push(payload);
  if (payload.status === "Completado") {
    createMaintenanceFromTask(payload);
  }
  qs("#taskFeedback").textContent = `Tarea guardada para ${payload.date}`;
  renderCalendar(qs("#planningMonth").value);
  renderKPIs();
  renderRecentMaintenance();
  renderLife();
  renderTaskDetails();
}

function deriveTaskStatus(task) {
  if (task.status === "Completado") return "Completado";
  const today = new Date().toISOString().slice(0, 10);
  if (task.date < today) return "Vencida";
  return task.status || "Planificado";
}

function renderTaskDetails() {
  const container = qs("#taskDetails");
  const dayTasks = tasks.filter((t) => t.date === state.planning.selectedDate);
  if (!dayTasks.length) {
    container.innerHTML = `<p class="muted">No hay tareas para ${state.planning.selectedDate}</p>`;
    return;
  }
  container.innerHTML = `
    <h4>Tareas del ${state.planning.selectedDate}</h4>
    ${dayTasks
      .map((t) => {
        const eq = equipment.find((e) => e.id === t.equipmentId);
        const status = deriveTaskStatus(t);
        return `<div class="task-row">
          <div>
            <strong>${eq?.code || "Equipo"}</strong> - ${t.type} (${status})<br/>
            <span class="muted">${eq?.name || ""} | ${eq?.finca || ""}</span><br/>
            <span class="muted">Resp: ${t.responsible || "Sin asignar"}</span>
          </div>
          <div class="task-actions">
            <button type="button" data-id="${t.id}" class="complete">Completar</button>
            <button type="button" data-id="${t.id}" class="reprogram">Reprogramar</button>
          </div>
        </div>`;
      })
      .join("")}
  `;
  container.querySelectorAll("button.complete").forEach((btn) => btn.addEventListener("click", () => completeTask(btn.dataset.id)));
  container.querySelectorAll("button.reprogram").forEach((btn) => btn.addEventListener("click", () => reprogramTask(btn.dataset.id)));
}

function completeTask(id) {
  const task = tasks.find((t) => t.id === id);
  if (!task) return;
  const cost = prompt("Costo del mantenimiento (USD)", task.cost || "");
  const responsible = prompt("Responsable", task.responsible || "");
  task.cost = Number(cost || 0);
  task.responsible = responsible || task.responsible;
  task.status = "Completado";
  createMaintenanceFromTask(task, { date: state.planning.selectedDate });
  const eq = equipment.find((e) => e.id === task.equipmentId);
  if (eq) {
    eq.lastMaintenance = state.planning.selectedDate;
    generatePreventiveTasksFor(eq.id);
  }
  renderKPIs();
  renderRecentMaintenance();
  renderLife();
  renderCalendar(qs("#planningMonth").value);
  renderTaskDetails();
}

function reprogramTask(id) {
  const task = tasks.find((t) => t.id === id);
  if (!task) return;
  const newDate = prompt("Nueva fecha (YYYY-MM-DD)", task.date);
  if (!newDate) return;
  task.date = newDate;
  state.planning.selectedDate = newDate;
  renderCalendar(qs("#planningMonth").value);
  renderTaskDetails();
}

function createMaintenanceFromTask(task, overrides = {}) {
  if (!task.createMaintenance) return;
  maintenanceRecords.unshift({
    id: crypto.randomUUID(),
    equipmentId: task.equipmentId,
    type: task.type === "Preventivo" ? "Preventivo" : task.type,
    responsible: task.responsible || "Sin responsable",
    parts: task.notes,
    cost: Number(task.cost || 0),
    date: overrides.date || task.date
  });
}

